#[cfg(test)]
mod tests {
    #[test]
    fn has_all_letters() {
        for c in 'А'..='Я' {
            assert!(super::get(c).is_some(), "{c}");
        }
        assert!(super::get('ё').is_some());
        assert_eq!(super::get('я'), super::get('Я'));
        assert!(super::get('a').is_none());
    }
}
